const toExport = (n) => 'fa' + n.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const label = (n) => n.split('-').map((p, i) => (i === 0 ? p[0].toUpperCase() + p.slice(1) : p)).join(' ');
const seen = new Set();
const rows = [];
const missing = [];
for (const name of NAMES) {
  if (seen.has(name)) continue;
  seen.add(name);
  const def = solid[toExport(name)];
  if (!def || typeof def.icon?.[4] !== 'string') { missing.push(name); continue; }
  const [w, h, , , d] = def.icon;
  rows.push(`  [${JSON.stringify(name)}, ${JSON.stringify(label(name))}, ${w}, ${h}, ${JSON.stringify(d)}],`);
}
const out = `// Generated by scripts/generate-services-icon-library.mjs — do not edit by hand.
// Icons from Font Awesome Free (solid), CC BY 4.0: https://fontawesome.com/license/free
// [name, label, viewBox width, viewBox height, path data]
export const SERVICE_ICON_LIBRARY: readonly (readonly [string, string, number, number, string])[] = [
${rows.join('\n')}
];
`;
writeFileSync(new URL('../components/portfolio/portfolio-services-icon-library.ts', import.meta.url), out);
console.log(`wrote ${rows.length} icons; missing: ${missing.join(', ') || 'none'}`);

